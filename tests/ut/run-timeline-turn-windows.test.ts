// Turns 顶部时间线「单击即跳」的数据面 IT（完整数据流：claude jsonl → adapter →
// turn-split → Prisma → GET /api/observe/run/[runId]/executions）：
//   /executions 的逐轮区间带 turnId——时间线点击「时刻 → 轮次」靠它在客户端
//   二分解析，不再为跳转去拉全量轮次；列表里没有行的命令附注轮（caveat /
//   stdout）标 hidden，不作跳转目标（跳过去选中态无处落地）。
import { describe, it, expect, afterEach, afterAll } from 'vitest';
import { NextRequest } from 'next/server';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { prisma } from '../setup';
import { POST } from '@/app/api/ingest/import-file/route';
import { GET } from '@/app/api/observe/run/[runId]/executions/route';
import { isCommandTail } from '@/lib/shared/command-parser';

const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'turn-windows-'));
const createdSessionIds: string[] = [];

interface ApiInterval { start: number; end: number; inferred?: boolean; turnId?: string; hidden?: boolean }
interface ApiAgent { executionId: string; isSubagent: boolean; activeIntervals: ApiInterval[] }

const SID = 'turn-windows-it';
const at = (m: number, s: number) => `2026-08-25T10:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}.000Z`;

/** 原生 claude jsonl：两轮正常问答 + 一次 /clear 命令（命令轮 + caveat 附注轮） */
function writeCapture(): string {
  const file = path.join(tmpDir, `${SID}.jsonl`);
  const user = (text: string, ts: string) => ({ type: 'user', message: { role: 'user', content: text }, timestamp: ts });
  const assistant = (text: string, ts: string, n: number) => ({
    type: 'assistant',
    message: { role: 'assistant', id: `msg_${SID}_${n}`, content: [{ type: 'text', text }], model: 'glm-5.2', usage: { input_tokens: 100, output_tokens: 20 } },
    timestamp: ts, duration_ms: 1500, stopReason: 'stop', ttftMs: 100,
  });
  fs.writeFileSync(file, [
    user('第一轮提问', at(0, 0)),
    assistant('第一轮回答', at(0, 5), 0),
    user('<command-name>/clear</command-name>\n<command-message>clear</command-message>\n<command-args></command-args>', at(2, 0)),
    user('<local-command-caveat>Caveat: The messages below were generated by the user while running local commands…</local-command-caveat>', at(2, 1)),
    user('第二轮提问', at(5, 0)),
    assistant('第二轮回答', at(5, 8), 1),
  ].map(l => JSON.stringify(l)).join('\n') + '\n');
  return file;
}

afterEach(async () => {
  for (const id of createdSessionIds.splice(0)) {
    try { await prisma.session.delete({ where: { id } }); } catch { /* ignore */ }
  }
});

afterAll(() => {
  fs.rmSync(tmpDir, { recursive: true, force: true });
});

describe('GET /api/observe/run/[runId]/executions — 逐轮区间带轮次身份（时间线跳转目标）', () => {
  it('solo run：每个区间带 turnId；命令附注轮标 hidden 且与库里的行一一对应；区间按起点升序', async () => {
    await prisma.session.deleteMany({ where: { taskId: SID } });
    const res = await POST(new NextRequest('http://localhost/api/ingest/import-file', {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ source: 'claude-jsonl', sessionId: SID, filePath: writeCapture() }),
    }));
    expect(res.status).toBe(200);
    const session = await prisma.session.findFirst({ where: { taskId: SID }, select: { id: true } });
    expect(session).not.toBeNull();
    createdSessionIds.push(session!.id);

    const apiRes = await GET(
      new NextRequest(`http://localhost/api/observe/run/${encodeURIComponent(`solo:${SID}`)}/executions`),
      { params: Promise.resolve({ runId: `solo:${SID}` }) },
    );
    expect(apiRes.status).toBe(200);
    const data = (await apiRes.json()) as { items: ApiAgent[] };
    const root = data.items.find(a => !a.isSubagent);
    expect(root).toBeTruthy();

    // 库里的行是真相源：区间 ↔ 行 一一对应（turnId 可解析到本会话的行）
    const rows = await prisma.turn.findMany({ where: { sessionId: session!.id }, select: { id: true, contentSummary: true, createdAt_ts: true } });
    const rowOf = new Map(rows.map(r => [r.id, r]));
    expect(root!.activeIntervals.length).toBeGreaterThanOrEqual(4);
    expect(new Set(root!.activeIntervals.map(iv => iv.turnId)).size).toBe(root!.activeIntervals.length);
    for (const iv of root!.activeIntervals) {
      expect(typeof iv.turnId).toBe('string');
      expect(iv.turnId!.length).toBeGreaterThan(0);
      const row = rowOf.get(iv.turnId!);
      expect(row, `区间 ${JSON.stringify(iv)} 的 turnId 不属于本会话`).toBeTruthy();
      // hidden 不自造口径：与轮次列表的行可见性同一把尺子（命令 caveat / stdout 附注）
      expect(iv.hidden ?? false).toBe(isCommandTail(row!.contentSummary ?? ''));
    }
    // 夹具里确有命令轮与 caveat 附注轮：命令轮有行（可跳），caveat 无行（不可跳）
    const byId = (pred: (text: string) => boolean) => rows.filter(r => pred(r.contentSummary ?? '')).map(r => r.id);
    const commandIds = byId(t => t.includes('<command-name>'));
    const caveatIds = byId(t => t.includes('<local-command-caveat>'));
    expect(commandIds.length).toBeGreaterThanOrEqual(1);
    expect(caveatIds.length).toBe(1);
    const intervalOf = (id: string) => root!.activeIntervals.find(iv => iv.turnId === id);
    expect(intervalOf(caveatIds[0]!)?.hidden).toBe(true);
    // 命令轮本身有行：区间照发、不标 hidden
    for (const id of commandIds) expect(intervalOf(id)?.hidden ?? false).toBe(false);

    // 升序 + 与行时间一致
    expect(root!.activeIntervals.length).toBe(rows.length); // 库里每一轮都有区间，一轮不漏
    const starts = root!.activeIntervals.map(iv => iv.start);
    expect(starts).toEqual([...starts].sort((a, b) => a - b));
    for (const iv of root!.activeIntervals) {
      const row = rowOf.get(iv.turnId!)!;
      if (!iv.inferred) expect(iv.start).toBe((row.createdAt_ts ?? new Date(0)).getTime());
    }
  });
});
