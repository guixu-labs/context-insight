from pathlib import Path
import sys


def acquire(directory: Path):
    directory.mkdir(parents=True, exist_ok=True)
    stream = (directory / "runtime.lock").open("a+b")
    try:
        if sys.platform == "win32":
            import msvcrt
            if stream.tell() == 0:
                stream.write(b"0")
                stream.flush()
            stream.seek(0)
            msvcrt.locking(stream.fileno(), msvcrt.LK_NBLCK, 1)
        else:
            import fcntl
            fcntl.flock(stream.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        return stream
    except OSError:
        stream.close()
        raise ValueError("Core data directory is already owned by another managed process") from None
